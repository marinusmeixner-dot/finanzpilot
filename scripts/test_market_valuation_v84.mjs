import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const data=JSON.parse(read('data/market-valuations-v84.json'));
const ideas=JSON.parse(read('data/ideas.json')).ideas;
const html=read('index.html');
const ui=read('market-insights-v82.js');
assert.equal(data.schema_version,1);
assert(data.stocks.length>=9,'Preserve original verified price snapshots');
assert(ideas.length>=9,'Support future curated research additions');
assert.equal(new Set(data.stocks.map(x=>x.id)).size,data.stocks.length,'Each quoted stock must have a unique identity');
assert(data.stocks.every(x=>ideas.some(i=>i.id===x.id)),'Each audited price record must have an issuer dossier');
assert(html.includes('market-valuation-v84.js?v=84')&&html.includes('market-valuation-v84.css?v=84'),'New iPhone assets are loaded');
assert(html.indexOf('valuation-v83.js?v=83')<html.indexOf('market-valuation-v84.js?v=84'),'Existing scenarios are initialized first');
assert(html.indexOf('market-valuation-v84.js?v=84')<html.indexOf('market-insights-v82.js?v=86'),'Comparable quotes are initialized before research dossiers');
assert(ui.includes('FinanzPilotMarketValue?.renderFor?.(idea.id)')&&ui.includes('FinanzPilotMarketValue?.bind?.(root)'),'Comparison is shown and bound in actual market research');
const events={},state={view:'marketidea'};
const window={addEventListener:(n,f)=>events[n]=f,render(){},FinanzPilotValuation:null};
const document={readyState:'loading',addEventListener:(n,f)=>events[n]=f};
const fetch=async()=>({ok:true,json:async()=>data});
const context=vm.createContext({window,document,state,fetch,Intl,Date,Map,Set,Promise,Math,Number,String,Array,URL,console});
vm.runInContext(read('market-valuation-v84.js'),context,{filename:'market-valuation-v84.js'});
const api=window.FinanzPilotMarketValue;
await api.load();
assert.equal(api.stocks.length,data.stocks.length,'Load all published price snapshots');
assert(api.summaryFor('kion').includes('KGV TTM')&&api.summaryFor('kion').includes(api.snapshot('kion').quote.date),'Research cards must display a dated, refreshed quote');
assert(api.summaryFor('microsoft').includes(api.snapshot('microsoft').quote.date));
for(const rec of api.stocks){
 const q=rec.quote,f=rec.fundamentals,derived=api.derive(rec);
 assert(/^\d{4}-\d{2}-\d{2}$/.test(q.date)&&Date.parse(q.date+'T12:00:00Z')<=Date.now(),'The quoted session must be a completed historical date');
 assert.equal(q.price_type,'regular_session_close');
 assert(['NASDAQ','XETRA'].includes(q.exchange));
 assert(q.source_url.startsWith('https://')&&f.source_url.startsWith('https://'));
 assert(Math.abs((f.operating_cf_m-f.capex_m)-f.free_cf_m)<=0.2,'FCF must reconcile from cash flow and CapEx');
 assert(Math.abs(derived.cap_m-q.close*f.shares_m)<1e-7,'Market cap from same-date price and shares');
 assert(Math.abs(derived.fcf_yield_pct-100*f.free_cf_m/derived.cap_m)<1e-7);
 assert(Math.abs(derived.net_cash_m-(f.cash_m-f.debt_m))<1e-7);
 assert(derived.pe>0);
 const page=api.renderFor(rec.id);
 assert(page.includes(rec.quote.date));
 assert(page.includes('Kurs × Aktien')&&page.includes('FCF-Rendite'));
 assert(page.includes('kein')||page.includes('Keine')||page.includes('nicht'));
 assert(page.includes('UMGEKEHRTE BEWERTUNGSFRAGE')&&page.includes('data-fp84-pe=')&&page.includes('data-fp84-discount='));
 assert(page.includes('Keine Vor- oder Nachbörse'));
 if(f.observed_date>q.date) assert(page.includes('Datenzeitpunkt beachten'),'Post-close fundamentals must carry an explicit look-ahead warning');
 assert(page.includes('Sekundäranbieter'));
 assert(!page.includes('Sofort kaufen'));
}
const ms=api.snapshot('microsoft');
const x=api.requiredEpsGrowth(ms.quote.close,ms.fundamentals.eps_ttm,3,27,10);
assert(Number.isFinite(x));
const reverse=api.projectedPrice(ms.fundamentals.eps_ttm,3,x,27,10);
assert(Math.abs(reverse-ms.quote.close)<1e-8,'Reverse valuation must mathematically solve the dated closing price');
const kion=api.snapshot('kion'),kionVal=api.derive(kion);
assert(Math.abs(kionVal.fcf_yield_pct-100*kion.fundamentals.free_cf_m/kionVal.cap_m)<1e-8,'KION FCF yield must derive from the current saved price, not a fixture');
const amz=api.snapshot('amazon');
assert(api.derive(amz).fcf_yield_pct<0,'Amazon negative cashflow not suppressed');
assert(api.renderFor('amazon').includes('Aktuell negativ'));
assert(api.snapshot('aixtron').quote.currency==='EUR'&&api.renderFor('aixtron').includes('Mrd. €'),'European sources retain EUR');
assert(api.requiredEpsGrowth(-4,1,3,20,10)===null);
assert(api.requiredEpsGrowth(50,0,3,20,10)===null);
assert(api.renderFor('does-not-exist').includes('Das datierte Kurs- und Kennzahlenpaket'));
// Interactive slider updates and reset.
const handlers={},els={};
const pe={dataset:{fp84Pe:'kion'},value:'12',addEventListener:(event,handler)=>handlers['pe:'+event]=handler};
const discount={dataset:{fp84Discount:'kion'},value:'10',addEventListener:(event,handler)=>handlers['disc:'+event]=handler};
const reset={addEventListener:(event,handler)=>handlers['reset:'+event]=handler};
for(const selector of ['[data-fp84-pe-label]','[data-fp84-discount-label]','[data-fp84-required]'])els[selector]={textContent:''};
const section={dataset:{fp84Module:'kion'},querySelectorAll:()=>[pe,discount],querySelector:s=>({'[data-fp84-reset]':reset,'[data-fp84-pe]':pe,'[data-fp84-discount]':discount})[s]||els[s]||null};
api.bind({querySelectorAll:()=>[section]});
pe.value='18';handlers['pe:input']();
assert(els['[data-fp84-pe-label]'].textContent.includes('18'));
const before=els['[data-fp84-required]'].textContent;
discount.value='14';handlers['disc:input']();
assert(els['[data-fp84-discount-label]'].textContent.includes('14'));
assert.notEqual(before,els['[data-fp84-required]'].textContent);
handlers['reset:click']();
assert.equal(Number(pe.value),12);
assert.equal(Number(discount.value),10);
console.log('V84 PASS: nine date-stamped source-backed closing prices, reconciled free cash flow, PE/FCF metrics, reverse EPS math, explicit limits, EUR and live sliders.');
