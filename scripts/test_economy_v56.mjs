import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=f=>fs.readFileSync(f,'utf8');
const cat=JSON.parse(read('data/specializations-v41.json'));
const SQL=read('supabase/economy_balance_v56.sql'),levels=read('levels-v55.js');
const missions=read('missions-v51.js'),streak=read('streak-v40.js');
const foundation=read('journey-v39.js'),hub=read('learning-hub-v41.js');
assert.equal(cat.skills.length,52);
assert.equal(cat.skills.reduce((n,x)=>n+x.lessons.length,0),156);
const byTier=new Map(),net=[];
for(const s of cat.skills){
 assert(Number.isInteger(s.tier)&&s.tier>=1&&s.tier<=5);
 assert.equal(s.cost,2*s.tier+1,s.id+' unlock price');
 assert.equal(s.rewardPoints,s.tier,s.id+' completed reward');
 assert(s.cost>s.rewardPoints,'No single skill creates net free FP '+s.id);
 assert(s.lessons.every((l,i)=>l.xp>=15&&l.xp<=50&&(!i||l.xp>=s.lessons[i-1].xp)),'Skill lesson XP must vary with learning demand');
 byTier.set(s.tier,(byTier.get(s.tier)||0)+1);net.push(s.cost-s.rewardPoints);
}
assert.deepEqual([...byTier.entries()].sort((a,b)=>a[0]-b[0]),[[1,9],[2,9],[3,11],[4,16],[5,7]]);
assert.equal(net.reduce((a,b)=>a+b,0),211,'Full 52 skill tree must be an FP sink.');
assert(SQL.includes("WHEN 1 THEN 3 WHEN 2 THEN 5 WHEN 3 THEN 7 WHEN 4 THEN 9 ELSE 11"));
assert(SQL.includes("WHEN 1 THEN 1 WHEN 2 THEN 2 WHEN 3 THEN 3 WHEN 4 THEN 4 ELSE 5"));
const alignment=read('supabase/economy_tier_alignment_v56.sql');
assert(alignment.includes("realrendite-kaufkraft")&&alignment.includes("etf-tracking-steuern"),'Irregular deeper ETF skills must match client difficulty tiers.');
assert(SQL.includes("v_reward_points:=2"),'Promotion should not inject escalating infinite FP.');
assert(SQL.includes("when 'daily' then 1 when 'weekly' then 3 else 1"),'Missions must have balanced server rewards');
assert(SQL.includes("v_bonus_points:=0"),'Promotions must not compound daily FP inflation');
for(const x of ['v_points:=2','v_points:=3','v_points:=4'])assert(SQL.includes(x));
assert(SQL.includes("v_fp:=case when mod(v_level_i,10)=0 then 2 when mod(v_level_i,5)=0 then 1 else 0 end;"));
assert(SQL.includes("100*(g.l-1)+10*(g.l-1)*(g.l-2)"));
assert(SQL.includes("when p_module_id in ('urteil-fakt-vs-deutung'"));
assert(SQL.includes("v_fp int:=case when p_module_id in ("));
assert(SQL.includes("on conflict(user_id,level) do nothing"),'Level prizes must be idempotent');
assert(SQL.includes("on conflict(user_id,module_id) do nothing"),'Foundation prizes must be idempotent');
assert(!/delete\s+from\s+public\.fp_(foundation_rewards_v55|level_rewards_v55)/i.test(SQL));
assert(levels.includes("const threshold=n=>100*(n-1)+10*(n-1)*(n-2)"));
assert(levels.includes("n%10===0?2:n%5===0?1:0"));
assert(levels.includes("const end=100;"),'Show complete roadmap to level 100.');
assert(levels.includes("for(const reached of freshLevels)"),'Real level-up effect even when no FP prize.');
assert(levels.includes("Number(result.fp_awarded)>0"));
assert(hub.includes("'Für '+s.cost+' FP auswählbar")&&hub.includes("current.cost+' Forschungspunkte"));
assert(!hub.includes("Skill für 3 Forschungspunkte auswählen"));
assert(missions.includes("<b>1 FP</b>")&&missions.includes("<b>3 FP</b>"));
assert(streak.includes("'+Number(result.today_points)+' FP'")&&streak.includes("TAGESBESUCH BESTÄTIGT"));
assert(foundation.includes("fp56-foundation-reward")&&foundation.includes("(6+2*n)"));
const threshold=n=>100*(n-1)+10*(n-1)*(n-2);
assert.deepEqual([1,2,3,4,5,10,20].map(threshold),[0,100,220,360,520,1620,5320]);
const foundationXP=3*[8,10,12,14,16,18].reduce((a,b)=>a+b,0);
assert.equal(foundationXP,234);
const skillsXP=cat.skills.flatMap(x=>x.lessons).reduce((a,b)=>a+b.xp,0);
assert(skillsXP>4600&&skillsXP<6900);
const actualLevel=[...Array(100)].reduce((last,_,i)=>threshold(i+1)<=foundationXP+skillsXP?i+1:last,1);
assert(actualLevel>=17&&actualLevel<=24,'Full curriculum should be a multi-month XP climb.');
const totalFP=6+17*2+[...Array(actualLevel)].reduce((a,_,i)=>a+(i+1===1?0:(i+1)%10===0?2:(i+1)%5===0?1:0),0);
assert(totalFP<100,'Non-recurring awards alone cannot unlock the full skill tree.');
console.log('V56 economy pass: '+cat.skills.length+' skills, '+net.reduce((a,b)=>a+b,0)+' net FP needed before lesson fees, '+foundationXP+' foundation XP, '+skillsXP+' specialization XP, max curriculum level '+actualLevel+', low passive FP, idempotent ledger and aligned UI.');
