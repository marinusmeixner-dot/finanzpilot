import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=file=>fs.readFileSync(file,'utf8');
const js=read('journey-v39.js'),css=read('journey-v39.css'),html=read('index.html');
const catalog=JSON.parse(read('data/journey-v39.json')),bank=JSON.parse(read('data/journey-questions-v55.json'));
const modules=catalog.stages.flatMap(s=>s.modules);
const local={};
const seed={completed:Object.fromEntries(modules.map(m=>[m.id,1700000000000])),lessons:{},selected:''};
local.finanzpilot_journey_v1=JSON.stringify(seed);
const events={};
const document={readyState:'loading',addEventListener(k,fn){events[k]=fn}};
const window={FinanzPilotCloud:{user:null},FinanzPilotNavigation:{route(){}},addEventListener(){},dispatchEvent(){},render(){}};
const cx=vm.createContext({window,document,localStorage:{getItem:k=>local[k]||null,setItem:(k,v)=>local[k]=v},
 fetch:async url=>({ok:true,json:async()=>String(url).includes('questions')?bank:catalog}),
 Event:class{constructor(type){this.type=type}},console,Date,Number,Math,Array,Object,Set,JSON});
vm.runInContext(js,cx);
const journey=window.FinanzPilotJourney;
await journey.load();
assert.equal(journey.modules.length,18,'V59 must preserve all 18 foundation modules.');
const render=(id,page=0)=>{journey.open(id);journey.state.lessons[id].page=page;return journey.renderFor('journeycourse')};
const lessonInfo=(html)=>html.replace(/<details class="fp59-glossary"[\s\S]*?<\/details>/g,'');
const etf=render('anlagearten');
assert(etf.includes('data-fp59-glossary')&&etf.includes('<dt>ETF</dt>'),'ETF has a collapsible definition on lesson page 1.');
assert(etf.includes('Exchange Traded Fund – börsengehandelter Fonds'),'The glossary gives German and original term.');
assert(!lessonInfo(etf).includes('ETF (Exchange Traded Fund)'),'No automatic parenthetical expansion in prose.');
const kgv=render('bewertungsvergleiche');
assert(kgv.includes('<dt>KGV</dt>'),'KGV glossary present.');
assert(!lessonInfo(kgv).includes('Kurs-Gewinn-Verhältnis (KGV)'),'Authored KGV parentheses converted to plain abbreviation.');
const margin=render('rechnen-marge',2);
assert(margin.includes('<dt>EBIT</dt>')&&margin.includes('Gewinn vor Zinsen und Steuern'),'EBIT defined in collapsible glossary on quiz pages.');
assert(!lessonInfo(margin).includes('EBIT (Earnings Before Interest and Taxes)'),'Quiz text only contains acronym, not inline expansion.');
const sources=render('analysieren-quellen',2);
for(const acronym of ['USD','EUR','EBITDA','EBIT'])assert(sources.includes('<dt>'+acronym+'</dt>'),'Source quiz glossary missing '+acronym);
assert(!lessonInfo(sources).includes('USD (US-Dollar)'),'Currency acronym not expanded inline.');
assert(!render('geld-wofuer').includes('data-fp59-glossary'),'No useless glossary when no abbreviations are used.');
journey.open('rechnen-marge');
let toggle;
const details={addEventListener(n,cb){if(n==='toggle')toggle=cb}};
journey.bind({querySelectorAll:()=>[],querySelector:s=>s==='[data-fp59-glossary]'?details:null});
assert.equal(typeof toggle,'function','The native accessible details state is tracked.');
toggle({currentTarget:{open:true}});
journey.state.lessons['rechnen-marge'].page=3;
assert(journey.renderFor('journeycourse').includes('data-fp59-glossary open'),'Expanded glossary stays open across pages.');
toggle({currentTarget:{open:false}});
assert(!journey.renderFor('journeycourse').includes('data-fp59-glossary open'),'Glossary can be collapsed.');
assert(css.includes('.fp59-glossary summary:focus-visible'),'Keyboard focus visible.');
assert(html.includes('journey-v39.js?v=80')&&/journey-v39[.]css[?]v=[0-9]+/.test(html),'Current foundation glossary JS and existing styles load with versioned iPhone cache URLs.');
assert(!js.includes("abbr+' ('"),'No automatic parenthesized term expansion');
console.log('V59 PASS: per-lesson relevant collapsible definitions, no inserted parentheticals, ECB/ETF/KGV/EBIT glossary, accessible, retained state, no changes to 18 lessons/progress.');
