import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const data=JSON.parse(read('data/opportunity-queue-v89.json'));
const radar=JSON.parse(read('data/research-radar-v86.json'));
const decisions=JSON.parse(read('data/research-decisions-v87.json'));
const html=read('index.html'),radarScript=read('market-radar-v86.js');
assert.equal(data.schema_version,1);
assert.equal(data.total_issuers,radar.candidates.length);
assert.equal(data.candidates.length,radar.candidates.length);
assert(data.candidates.length>9,'No fixed nine-company shortlist');
assert.equal(data.total_issuers,decisions.rows.length);
assert.equal(new Set(data.candidates.map(x=>x.id)).size,data.total_issuers);
assert(data.spotlight_ids.every(id=>data.candidates.some(x=>x.id===id)));
assert(data.candidates.every(x=>x.next_checks.length===3&&x.company&&x.ticker&&x.diligence_posture.includes('keine Kauf')));
assert(data.candidates.every(x=>x.bucket!=='review_now'||['news_catalyst','fundamental_watch'].includes(x.review_kind)));
assert(data.candidates.filter(x=>x.review_kind==='news_catalyst').every(x=>x.evidence_url?.startsWith('https://')&&x.evidence_age_days<=21));
assert(data.candidates.filter(x=>x.review_kind==='technical_only').every(x=>!x.evidence_url));
assert(data.candidates.every(x=>x.bucket!=='archived'||x.review_kind==='archived'));
assert.equal(Object.values(data.bucket_counts).reduce((a,b)=>a+b,0),data.total_issuers);
assert(html.includes('market-priorities-v89.js?v=89')&&html.includes('market-priorities-v89.css?v=89'));
assert(html.includes('market-radar-v86.js?v=89'));
assert(html.indexOf('market-priorities-v89.js?v=89')<html.indexOf('market-radar-v86.js?v=89'));
assert(radarScript.includes('FinanzPilotPriorities?.summary?.()'));
assert(radarScript.includes('FinanzPilotPriorities?.detail?.(c.id)'));
assert(radarScript.includes('FinanzPilotPriorities?.bind?.(root)'));
const listeners={},routes=[],doc={readyState:'loading',addEventListener:(name,fn)=>listeners[name]=fn};
const win={addEventListener:(name,fn)=>listeners[name]=fn,render(){},
  FinanzPilotInsights:{openIdea:id=>routes.push(id)}};
const ctx=vm.createContext({window:win,document:doc,fetch:async()=>({ok:true,json:async()=>data}),URL,Date,Map,Set,Math,Intl,Promise,String,Array,console,state:{view:'marketideas'}});
vm.runInContext(read('market-priorities-v89.js'),ctx);
const api=win.FinanzPilotPriorities;
await api.load();
assert.equal(api.items.length,data.total_issuers);
const list=api.summary();
for(const label of ['quellenbasierte','Research','Unternehmen','zuerst prüfen','keine Rangliste'])assert(list.toLowerCase().includes(label.toLowerCase()),label);
assert(list.includes('data-fp89-open='));
const id=data.spotlight_ids[0],item=api.get(id);
assert(item&&item.bucket==='review_now');
const detail=api.detail(id);
assert(detail.includes('Konkrete nächste Rechercheschritte')&&detail.includes('ETF')&&detail.includes('Gegenprüfung'));
assert(detail.includes(item.next_checks[0]));
assert(detail.includes('data-fp89-open')===false,'Detail does not offer dead navigation buttons');
let handler;const button={dataset:{fp89Open:id},addEventListener:(event,fn)=>{assert.equal(event,'click');handler=fn}};
api.bind({querySelectorAll:selector=>selector==='[data-fp89-open]'?[button]:[]});
handler();assert.deepEqual(routes,[id]);
console.log('V89 PASS: full-universe source-first diligence queue, 3 proof steps each, genuine fresh-source priorities, ETF alternatives and working links.');
