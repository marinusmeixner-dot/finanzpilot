import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('index.html'),app=read('app.js'),nav=read('ux-v15.js'),market=read('market-v34.js');
const profiles=JSON.parse(read('data/company-profiles-v82.json'));
const ideas=JSON.parse(read('data/ideas.json'));
const research=JSON.parse(read('data/research.json'));
assert.equal(profiles.schema_version,1);
assert(Object.keys(profiles.companies).length>=20,'Meaningful coverage for the major company news tickers');
assert(ideas.ideas.length>=3,'Must preserve the researched ideas');
assert(html.includes('market-insights-v82.js?v=86')&&html.includes('market-insights-v82.css?v=82'),'Module must be loaded');
assert(html.includes('market-v34.js?v=82')&&html.includes('app.js?v=82'),'Modified modules must bypass iOS cache');
assert(nav.includes("['marketideas','Aktienideen'"),'Research belongs in the existing Märkte tab');
assert(nav.includes("marketidea:'marketideas'"),'Research detail is a child of ideas');
assert(app.includes("FinanzPilotInsights.renderIdeas()")&&app.includes("FinanzPilotInsights.renderIdea()"),'Real pages are rendered');
assert(market.includes("FinanzPilotInsights?.companyContext?.(n,false)"));
assert(market.includes("FinanzPilotInsights?.articleContext?.(n)"));
assert(market.includes("['companies','Unternehmen']")&&market.includes("['all','Alle News']"));
assert(market.includes('FinanzPilotInsights?.bind?.(root)'),'Company research links must be clickable');
const seen=[],events={};
const win={addEventListener:(event,cb)=>events[event]=cb,render(){},FinanzPilotNavigation:{route:s=>seen.push(s)}};
const doc={readyState:'loading',addEventListener:(event,cb)=>events[event]=cb};
const localStorage={getItem:()=>null,setItem(){}};
const state={view:'marketideas'};
const fetch=async url=>({ok:true,json:async()=>String(url).includes('company-profiles-v82')?profiles:String(url).includes('ideas.json')?ideas:research});
const context=vm.createContext({window:win,document:doc,localStorage,state,fetch,URL,Date,Intl,Math,Number,String,Array,Map,Set,Promise,console});
vm.runInContext(read('market-insights-v82.js'),context);
const api=win.FinanzPilotInsights;
await api.load();
const list=api.renderIdeas();
assert(list.includes('Aktien auf dem Radar'));
assert(list.includes('AIXTRON')&&list.includes('KION')&&list.includes('Cognex'),'Existing researched ideas remain visible');
assert(list.includes('Gegenargumente')&&list.includes('Investmentthese ansehen'));
assert(api.openIdea('aixtron'));
assert.equal(seen.at(-1),'marketidea');
const dossier=api.renderIdea();
for(const str of ['GESCHÄFTSMODELL','INVESTMENTTHESE','RISIKEN','BEWERTUNG','Original-Finanzbericht'])assert(dossier.includes(str),'Dossier missing '+str);
assert(dossier.includes('Fertigungsanlagen')&&dossier.includes('Umsatz'),'Dossier must explain the business and contain sourced financial context');
assert(!dossier.includes('Jetzt kaufen'),'No unsupported buy calls');
const story={title:'BMW Quartal',symbols:['BMW.DE'],why:'Quartalsbericht veröffentlicht',impact:'Marge könnte sinken'};
assert(api.companyContext(story,true).includes('Premiumautos')&&api.companyContext(story,true).includes('Wie verdient das Unternehmen Geld?'));
assert(api.articleContext(story).includes('WAS IST PASSIERT?')&&api.articleContext(story).includes('WAS KÖNNTE DAS BEDEUTEN?'));
assert(api.companyContext({symbols:[]},true)==='');
assert(api.companyContext({symbols:['UNKNOWN.TEST']}).includes('Unternehmensprofil wird überprüft'),'Do not invent unknown business models');
console.log('V82 PASS: linked market routes, company profiles, source-backed news context, actual investment dossiers and cautious valuation language.');
