import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const src=read('terms-v73.js'),window={},document={readyState:'loading',addEventListener(){}};
vm.runInNewContext(src,{window,document});
const terms=window.FinanzPilotTerms;
assert(terms,'Glossary module initialized');
const rows=terms.entries('In deinem Bericht fehlt die Entwicklung des Forderungsbestands. Und was passiert im Working Capital?');
assert(rows.some(x=>x.label==='Forderungsbestand'&&x.definition.includes('Kundenrechnungen')));
assert(rows.some(x=>x.label==='Working Capital'&&x.definition.includes('Verbindlichkeiten')));
const xss=terms.markup([{label:'<b>Test</b>',definition:'<&>'}]);
assert(xss.includes('&lt;b&gt;Test&lt;/b&gt;')&&xss.includes('&lt;&amp;&gt;'));
assert.equal(terms.entries('Eine fachlich gut formulierte Frage ohne finanzielle Fachbegriffe.').length,0,'No unrelated glossary');
const bank=JSON.parse(read('data/journey-questions-v55.json'));
const all=Object.values(bank.questions).flat();
assert.equal(all.length,36,'Do not change number of foundation questions');
assert(terms.entries(all.filter(x=>x.prompt.includes('Forderungsbestands')).flatMap(x=>[x.prompt,...x.options])).some(x=>x.label==='Forderungsbestand'));
assert(src.includes('.fp46-study-panel')&&src.includes('.fp-training-case')&&src.includes('.fp51-question')&&src.includes('.academy-lesson-panel'),'Shared definitions cover other question renderers');
const foundation=read('journey-v39.js');
assert(foundation.includes('termApi?.entries?.(quiz,30)'), 'Foundation merges question-specific glossary into the original panel');
assert(foundation.includes('data-fp59-glossary'),'Original accessible collapsible glossary remains');
const index=read('index.html'),version=JSON.parse(read('version.json')).version;
assert(index.includes('terms-v73.js?v=73'),'All learning views load glossary script');
assert(index.includes('journey-v39.js?v=80'),'Foundation glossary module keeps its dedicated version after an unrelated home update');
assert(index.includes('ui-v43.css?v='+version)&&index.includes('manifest.webmanifest?v='+version));
console.log('V73 PASS: 193 term definitions, Forderungsbestand and Working Capital on foundation questions, neutral explanations across learning views.');
